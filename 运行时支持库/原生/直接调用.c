#include "直接调用.h"

豫言直接退出域 *豫言_直接退出顶 = NULL;
static uint64_t 下次激活号 = 1;

豫言值 豫言_直接进入退出域(豫言直接退出域 *域, volatile 豫言值 *结果槽) {
    if (下次激活号 > INT64_MAX) 报错并中止("动态退出激活号耗尽");
    域->根顶 = 豫言_影子根顶;
    域->前域 = 豫言_直接退出顶;
    域->结果槽 = 结果槽;
    域->激活号 = 下次激活号++;
    豫言_直接退出顶 = 域;
    return 整数转豫言值(域->激活号);
}

_Noreturn void 豫言_直接提前退出(豫言值 令牌, 豫言值 结果) {
    uint64_t 激活号 = 豫言值转整数(令牌);
    豫言直接退出域 *域 = 豫言_直接退出顶;
    /* 文言：循活域验令，不解已亡之址。汉语：在解引用令牌前确认其属于当前动态链；不支持保存 continuation。 */
    while (域 != NULL && 域->激活号 != 激活号) 域 = 域->前域;
    if (域 == NULL) {
        报错并中止("continuation 已离开动态范围");
        abort();
    }
    *域->结果槽 = 结果;
    豫言_恢复影子根栈(域->根顶);
    豫言_直接退出顶 = 域;
    longjmp(域->跳转, 1);
}
