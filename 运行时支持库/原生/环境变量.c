豫言值 豫言_获取环境变量(豫言值 名称) {
    const char *环境值 = getenv(豫言值转字符串(名称));
    if (环境值 == NULL) {
        豫言值 值组[] = {
            爻转豫言值(false),
            复制字节为豫言值(0, ""),
        };
        return 元组转豫言值(2, 值组);
    }

    豫言值 值组[] = {
        爻转豫言值(true),
        复制字节为豫言值(strlen(环境值), 环境值),
    };
    return 元组转豫言值(2, 值组);
}
