豫言值* 豫言栈开始;
豫言值 *豫言栈垃圾回收阈值;
豫言值* 豫言栈结束;
豫言值* 豫言_栈指针;
// 栈大小以豫言值槽位计数；每个豫言值占十六字节。
/* 网页汇编小其栈。Wasm 初始栈为四兆字节，原生默认值不变。 */
#ifdef __wasi__
#define 初始栈槽位数量 (4 * 1024 * 1024 / 16)
#else
#define 初始栈槽位数量 (32 * 1024 * 1024)
#endif
uint64_t 栈大小 = 初始栈槽位数量;
double 栈垃圾回收阈值百分比 = 80.0;
pthread_mutex_t 豫言栈指针锁 = PTHREAD_MUTEX_INITIALIZER;
豫言函数指针类型 当前豫言函数;
bool 运行时调试标记 = false;

豫言值 豫言_函数调用前调试信息(豫言值 新栈指针值, 豫言值 下个函数指针, 豫言值 栈占用参数){

    豫言函数指针类型 下个函数 = 豫言值转函数指针(下个函数指针);
    uint64_t 栈占用 = 豫言值转整数(栈占用参数);
    豫言值 *新栈指针 = 豫言值转栈指针(新栈指针值);
    if (豫言_栈指针 < 新栈指针) {
        assert(豫言值转栈指针(新栈指针[0]) == 豫言_栈指针);
    } else {
        assert(豫言_栈指针 == 新栈指针);
    }
    assert(豫言栈开始 <= 豫言_栈指针 && 豫言_栈指针 <= 豫言栈垃圾回收阈值);
    assert(豫言栈开始 <= 新栈指针 && 新栈指针 <= 豫言栈垃圾回收阈值);
    assert(当前堆 <= 豫言_当前分配指针 && 豫言_当前分配指针 <= 豫言_当前堆垃圾回收阈值);
    验证当前堆();
    验证豫言栈();

    if (运行时调试标记)
    {
        fprintf(stderr, "调用函数，返回栈指针：");
        打印豫言值(新栈指针[0], 0);
        fprintf(stderr, "（偏移 %td）", 豫言值转栈指针(新栈指针[0]) - 豫言栈开始);
        fprintf(stderr, "\n当前栈指针 %p（偏移 %td），下个栈指针 %p（偏移 %td）",
                豫言_栈指针, 豫言_栈指针 - 豫言栈开始, 新栈指针, 新栈指针 - 豫言栈开始);
        fprintf(stderr, "\n返回函数指针：");
        打印豫言值(新栈指针[1], 0);
        fprintf(stderr, "\n返回续延编号：");
        打印豫言值(新栈指针[2], 0);
        fprintf(stderr, "\n返回参数：");
        打印豫言值(新栈指针[3], 0);
        fprintf(stderr, "\n调用块编号：");
        打印豫言值(新栈指针[4], 0);
        fprintf(stderr, "\n被调用函数：");
        打印豫言值(下个函数指针, 0);
        if (栈占用 <= 5)
        {
            fprintf(stderr, "\n（无参数）");
        } else {
            for (int 序数 = 5; 序数 < 栈占用; 序数++) {
                fprintf(stderr, "\n参数 %d：", 序数 - 5);
                打印豫言值(新栈指针[序数], 0);
            }
        }
        fprintf(stderr, "\n");
    }

    return 单元转豫言值();
}
// 每次调用豫言函数前先检查栈空间，并在需要时执行垃圾回收。
豫言值 豫言_函数调用前垃圾回收(豫言值 新栈指针, 豫言值 栈占用参数){
    uint64_t 栈占用 = 豫言值转整数(栈占用参数);
    assert (栈占用 >= 5);

    assert(豫言_栈指针 <= 豫言值转栈指针(新栈指针));
    豫言_栈指针 = 豫言值转栈指针(新栈指针);
    assert(豫言_当前分配指针 > 豫言_当前堆垃圾回收阈值);
    if (豫言_当前分配指针 > 当前堆结束)
    {
        fprintf(stderr, "[运行时栈] 堆空间已经用尽，且当前尚不能执行垃圾回收。\n"
                        "堆开始 %p，堆结束 %p，垃圾回收阈值 %p，分配指针 %p\n"
                        "堆大小 %td，堆偏移 %td，回收点大小 %td\n",
                当前堆, 当前堆结束, 豫言_当前堆垃圾回收阈值, 豫言_当前分配指针,
                当前堆结束 - 当前堆,
                豫言_当前分配指针 - 当前堆,
                豫言_当前堆垃圾回收阈值 - 当前堆);
        报错并中止("主堆空间已经用尽；请降低垃圾回收阈值，使回收更早发生");
        return 单元转豫言值();
    }
    if (豫言_栈指针 >= 豫言栈垃圾回收阈值) {
        报错并中止("豫言栈已溢出，请增大栈空间后重试");
        return 单元转豫言值();
    }
    豫言_栈指针 += 栈占用;
    执行垃圾回收();
    豫言_栈指针 -= 栈占用;
    return 单元转豫言值();
}


uint64_t 上个续延异常编号 = 0;
豫言值* 续延异常表 = NULL;
uint64_t 续延异常表大小 = 0;
豫言值 豫言_获取下个续延异常编号()
{
    uint64_t 下个续延异常编号 = 上个续延异常编号 + 1;
    if (续延异常表大小 <= 下个续延异常编号) {
        if (续延异常表大小 == 0) {
            续延异常表大小 = 16;
        } else{
            续延异常表大小 *= 2;
        }
        续延异常表 = (豫言值*) realloc(续延异常表, 续延异常表大小 * sizeof(豫言值));
    }
    上个续延异常编号 = 下个续延异常编号;

    return 整数转豫言值(下个续延异常编号);
}

/*
续延异常表保存栈指针。抛出异常等价于返回到某个特定调用点。
*/

#define 栈记忆上限 100000
豫言值 栈记忆[栈记忆上限];

豫言值 豫言_设置续延异常处理器(豫言值 编号, 豫言值 栈指针地址)
{
    // 调用函数只能返回到自己的返回地址。
    assert(豫言值转栈指针(栈指针地址) == 豫言_栈指针);
    续延异常表[豫言值转整数(编号)] = 栈指针地址;
    if (豫言值转整数(编号) < 栈记忆上限) {
        // 保存返回地址，以便读取处理器时验证。
        栈记忆[豫言值转整数(编号)] = 豫言值转栈指针(栈指针地址)[1];
    }
    return 单元转豫言值();
}

豫言值 豫言_获取续延异常处理器(豫言值 编号)
{
    豫言值 返回值 = 续延异常表[豫言值转整数(编号)];
    // 调用函数不应返回到当前栈指针之后的位置。
    assert(豫言值转栈指针(返回值) <= 豫言_栈指针);
    if (豫言值转整数(编号) < 栈记忆上限) {
        assert(栈记忆[豫言值转整数(编号)] == 豫言值转栈指针(返回值)[1]);
    }
    return 返回值;
}


void 豫言程序退出续延(豫言值 栈顶, 豫言值 当前分配参数){
    豫言值 *局部栈指针 = 豫言值转栈指针(栈顶);
    豫言_栈指针 = 局部栈指针;
    assert(豫言_栈指针 == 豫言栈开始);
    assert(豫言值转整数(豫言_栈指针[4]) == 1);
    return;
}

#define 运行时递归验证 true
int64_t 启动豫言运行时() {
    运行时调试标记 = getenv("YY_DEBUG_FLAG") != NULL && strcmp(getenv("YY_DEBUG_FLAG"), "1") == 0;
    // 根据环境变量调整初始栈大小。
    if (getenv("YY_GC_INITIAL_STACK_SIZE_MB") != NULL ) {
        const char* 请求大小 = getenv("YY_GC_INITIAL_STACK_SIZE_MB");
#ifdef __wasi__
        /* 兆字节化槽位。Wasm 参数单位为 MiB，限制在固定内存预算内。 */
        int 请求兆字节 = atoi(请求大小);
        if (请求兆字节 <= 0 || 请求兆字节 > 32) 报错并中止("网页汇编栈大小须为一至三十二 MiB");
        栈大小 = (uint64_t)请求兆字节 * 1024 * 1024 / sizeof(豫言值);
#else
        栈大小 = atoi(请求大小) * 1024 * 1024;
#endif
    }

    if (栈大小 != 初始栈槽位数量) {
        fprintf(stderr, "豫言初始栈已设为 %.0f MB\n", (double) 栈大小 * sizeof(豫言值) / (1024 * 1024));
    }

    豫言栈开始 = (豫言值*) malloc(栈大小 * sizeof(豫言值));
    豫言栈结束 = 豫言栈开始 + 栈大小;
    // 待办：允许栈按需增长。
    豫言栈垃圾回收阈值 = 豫言栈开始 + (uint64_t) (栈大小 * 栈垃圾回收阈值百分比 / 100.0);
    豫言_栈指针 = 豫言栈开始;

    if (启用性能分析) {
        // 启动性能分析器();
    }

    /**
     * 豫言调用约定在栈中依次保存：
     * 一、上一个栈指针；
     * 二、上一个函数指针；
     * 三、续延编号；
     * 四、函数参数；
     * 五、调用块编号。
     * 被调用者把返回值写回当前栈帧的第零项。
    */
    豫言栈开始[0] = 栈指针转豫言值(豫言栈开始);
    豫言栈开始[1] = 函数指针转豫言值(豫言程序退出续延);
    豫言栈开始[2] = 整数转豫言值(1);
    豫言栈开始[3] = 单元转豫言值();
    豫言栈开始[4] = 整数转豫言值(1);

    豫言值 初始栈值 = 栈指针转豫言值(豫言栈开始);
    豫言值 初始分配值 = 运行时堆指针转豫言值(豫言_当前分配指针);
    调用豫言程序入口(初始栈值, 初始分配值);

    return 0;
}
