#include "公共包含.h"
extern int 全局参数数量;
extern char **全局参数值;
/* 文言：两途共辨入参，入口各持其值。汉语：旧稳定种子与统一原生入口共用参数处理，避免链接旧 main。 */
// 处理以“@豫言:”开头的运行时参数。
void 处理豫言参数(int 参数数量, char* 参数值[]) {
    char* 程序名 = 参数值[0];
    int 已处理参数数量 = 0;
    for (int 序数 = 1; 序数 < 参数数量; 序数++)
    {
        if (strncmp(参数值[序数], "@豫言:启用性能分析=1", sizeof("@豫言:启用性能分析=1") - 1) == 0) {
            启用性能分析 = true;
            已处理参数数量++;
        }
    }

    // 从用户可见的参数中排除已经处理的运行时参数。
    全局参数数量 -= 已处理参数数量;
    全局参数值 += 已处理参数数量;

    // 保证第一个参数仍然是程序名。
    全局参数值[0] = 程序名;
}


