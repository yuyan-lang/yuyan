#include "垃圾回收器.h"
#include "影子根栈.h"

豫言影子根帧 *豫言_影子根顶 = NULL;

void 豫言_进入影子根帧(豫言影子根帧 *帧, volatile 豫言值 *槽, uint64_t 数) {
    /* 文言：先定诸槽，后联其帧。汉语：未写入的槽必须为单元，GC 不得扫描未初始化内存。 */
    for (uint64_t 序 = 0; 序 < 数; ++序) 槽[序] = 单元转豫言值();
    帧->根槽 = 槽;
    帧->根数 = 数;
    帧->前帧 = 豫言_影子根顶;
    豫言_影子根顶 = 帧;
}

void 豫言_离开影子根帧(豫言影子根帧 *帧) {
    if (豫言_影子根顶 != 帧) 报错并中止("影子根帧退出次序错误");
    豫言_影子根顶 = 帧->前帧;
}

void 豫言_恢复影子根栈(豫言影子根帧 *目标) {
    /* 文言：验其尚在，然后退链。汉语：必须在机器栈展开之前调用；目标只能是当前链中的祖先或空。 */
    豫言影子根帧 *帧 = 豫言_影子根顶;
    while (帧 != 目标) {
        if (帧 == NULL) 报错并中止("提前退出的影子根目标已失效");
        帧 = 帧->前帧;
    }
    豫言_影子根顶 = 目标;
}

void 豫言_影子根安全点(void) {
    /* 文言：存活之值皆已入根，乃可迁堆。汉语：调用前登记所有跨此点存活的引用，调用后从根槽重读。 */
    豫言_影子根检查();
}

void 豫言_影子根慢回收(void) { 执行垃圾回收(); }
