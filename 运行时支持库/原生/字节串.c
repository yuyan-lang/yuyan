#include "公共包含.h"


豫言值 豫言_字节串_空(void) {
    return 分配豫言_字节串缓冲区(0);
}

豫言值 豫言_字节串_长度(豫言值 字节串) {
    return 整数转豫言值((int64_t)获取豫言_字节串长度(字节串));
}

豫言值 豫言_字节串_取字节(豫言值 字节串, 豫言值 序数参数) {
    int64_t 序数 = 豫言值转整数(序数参数);
    uint64_t 长度 = 获取豫言_字节串长度(字节串);
    if (序数 < 0 || (uint64_t)序数 >= 长度) {
        报错并中止("字节串取字节：序数越界");
    }
    return 整数转豫言值(豫言值转字节串指针(字节串)[序数]);
}

豫言值 豫言_字节串_从字符串(豫言值 字符串) {
    // 值不可变，文本与字节串在 C 运行时中共用表示，无需复制。
    return 字符串;
}

豫言值 豫言_字节串_单字节(豫言值 字节参数) {
    int64_t 字节 = 豫言值转整数(字节参数);
    if (字节 < 0 || 字节 > UINT8_MAX) {
        报错并中止("构造单字节串：字节必须在零至二百五十五之间");
    }
    unsigned char 值 = (unsigned char)字节;
    return 复制字节为豫言值(1, &值);
}

豫言值 豫言_字节串_拼接(豫言值 左串, 豫言值 右串) {
    uint64_t 左长度 = 获取豫言_字节串长度(左串);
    uint64_t 右长度 = 获取豫言_字节串长度(右串);
    if (左长度 > UINT32_MAX - 右长度) {
        报错并中止("拼接字节串：结果长度超过运行时上限");
    }

    豫言值 返回值 = 分配豫言_字节串缓冲区(左长度 + 右长度);
    unsigned char *目标 = 豫言值转字节串指针(返回值);
    if (左长度 > 0) {
        memcpy(目标, 豫言值转字节串指针(左串), 左长度);
    }
    if (右长度 > 0) {
        memcpy(目标 + 左长度, 豫言值转字节串指针(右串), 右长度);
    }
    return 返回值;
}
