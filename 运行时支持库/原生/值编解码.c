void 打印豫言值(豫言值 待打印值, uint64_t 深度) {
    if (深度 > 10) {
        fprintf(stderr, "...");
        return;
    }

    switch (获取豫言值类型(待打印值))
    {
    case 空值类型标记:
        fprintf(stderr, "（空值）");
        break;
    case 元组类型标记:
        fprintf(stderr, "元组(%" PRIu64 "): [", 获取豫言元组长度(待打印值));
        for (int 序数 = 0; 序数 < 获取豫言元组长度(待打印值); 序数 ++){
            打印豫言值(读取元组(待打印值, 序数), 深度 + 1);
            if (序数 != 获取豫言元组长度(待打印值) - 1){
                fprintf(stderr, ", ");
            }
        }
        fprintf(stderr, "]");
        break;
    case 整数类型标记:
        fprintf(stderr, "整数：%" PRId64 , 豫言值转整数(待打印值));
        break;
    case 小数类型标记:
        fprintf(stderr, "小数：%f", 豫言值转小数(待打印值));
        break;
    case 静态字符串类型标记:
        fprintf(stderr, "静态字符串：%s", 豫言值转字符串(待打印值));
        break;
    case 爻类型标记:
        fprintf(stderr, "爻：%s", 豫言值转爻(待打印值) ? "阳" : "阴");
        break;
    case 函数指针类型标记:
        fprintf(stderr, "函数指针：%p", 豫言值转函数指针(待打印值));
        break;
    case 静态对象指针类型标记:
        fprintf(stderr, "静态对象指针：%p", 豫言值转静态指针(待打印值));
        break;
    case 栈指针类型标记:
        fprintf(stderr, "栈指针：%p", 豫言值转栈指针(待打印值));
        break;
    case 转移地址类型标记:
        fprintf(stderr, "转移地址：%p", 豫言值转转移地址(待打印值));
        break;
    case 堆字符串头类型标记:
        fprintf(stderr, "堆字符串头：%s", 豫言值转字符串(待打印值));
        break;
    case 堆字符串类型标记:
        fprintf(stderr, "堆字符串：%s", 豫言值转字符串(待打印值));
        break;
    case 构造器元组类型标记:
        fprintf(stderr, "<构造器(%" PRIu64 ")：", 获取构造器序数(待打印值));
        打印豫言值(原始元组转豫言值(获取构造器元组长度(待打印值), 豫言值转构造器元组(待打印值)), 深度 + 1);
        fprintf(stderr, ">");
        break;

    default:
        fprintf(stderr, "未知类型：%" PRIu64 , 获取豫言值类型(待打印值));
        break;
    }

}
