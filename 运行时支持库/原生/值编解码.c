// 字节长度包含结尾空字符。
豫言值 分配豫言_字符串缓冲区(uint64_t 字节长度) {
    uint64_t 实际大小 = 字符串缓冲长度转块数(字节长度);
    豫言值* 缓冲区指针 = 垃圾回收堆分配块(实际大小);
    豫言值 头 = 0;
    设置豫言值原始长度(&头, 字节长度);
    设置豫言值类型(&头, 堆字符串头类型标记);
    缓冲区指针[0] = 头;
    豫言值 返回值 = (豫言值)缓冲区指针;
    设置豫言值类型(&返回值, 堆字符串类型标记);
    设置豫言值原始长度(&返回值, 字节长度);
    return 返回值;
}

// 字节长度必须包含结尾空字符。
豫言值 复制字符串为豫言值(uint64_t 字节长度, const char * 字符串){
    assert(strlen(字符串) == 字节长度 - 1);
    豫言值 返回值 = 分配豫言_字符串缓冲区(字节长度);
    char* 实际字符串指针 = 豫言值转堆字符串指针(返回值);
    memcpy(实际字符串指针, 字符串, 字节长度);
    return 返回值;
}

