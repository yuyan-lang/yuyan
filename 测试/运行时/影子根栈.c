#include "垃圾回收器.h"
#include "影子根栈.h"
#include "直接调用.h"
#include <setjmp.h>

/* 文言：此入口唯验根迁，不启旧程序。汉语：链接运行时归档所需的占位程序入口。 */
void 豫言_程序入口(豫言值 栈, 豫言值 堆) { (void)栈; (void)堆; }

static jmp_buf 返回点;

static void 嵌套退出(豫言影子根帧 *目标) {
    豫言值 槽[2];
    豫言影子根帧 帧;
    豫言_进入影子根帧(&帧, 槽, 2);
    槽[0] = 分配豫言元组(1);
    写入堆对象(槽[0], 0, 整数转豫言值(99));
    执行垃圾回收();
    /* 文言：未去真帧先复根链。汉语：模拟动态提前退出，避免 GC 后续遍历失效栈帧。 */
    豫言_恢复影子根栈(目标);
    longjmp(返回点, 1);
}

static void 直接嵌套退出(豫言值 令牌) {
    豫言值 槽[1];
    豫言影子根帧 帧;
    豫言_进入影子根帧(&帧, 槽, 1);
    槽[0] = 分配豫言元组(1);
    写入堆对象(槽[0], 0, 整数转豫言值(73));
    执行垃圾回收();
    豫言_直接提前退出(令牌, 槽[0]);
}

int main(void) {
    初始化垃圾回收器();
    /* 文言：旧栈设空，唯验新根。汉语：不使用旧虚拟栈保活测试对象。 */
    豫言值 空栈[1];
    豫言栈开始 = 豫言_栈指针 = 空栈;
    豫言栈结束 = 空栈 + 1;
    /* 文言：越返所改者勿居自动存储。汉语：根槽会被嵌套 GC 改写，静态存储避免 setjmp/longjmp 的自动变量不确定值规则。 */
    static 豫言值 槽[3];
    豫言影子根帧 帧;
    豫言_进入影子根帧(&帧, 槽, 3);
    assert(槽[2] == 单元转豫言值());
    槽[0] = 分配豫言元组(1);
    写入堆对象(槽[0], 0, 整数转豫言值(42));
    槽[1] = 槽[0];
    uintptr_t 旧址 = (uintptr_t)豫言值转元组(槽[0]);
    执行垃圾回收();
    assert((uintptr_t)豫言值转元组(槽[0]) != 旧址);
    assert(槽[0] == 槽[1]);
    assert(豫言值转整数(豫言值转元组(槽[0])[0]) == 42);
    if (setjmp(返回点) == 0) 嵌套退出(&帧);
    assert(豫言_影子根顶 == &帧);
    执行垃圾回收();
    assert(豫言值转整数(豫言值转元组(槽[0])[0]) == 42);
    豫言直接退出域 域;
    豫言值 令牌 = 豫言_直接进入退出域(&域, &槽[2]);
    if (setjmp(域.跳转) == 0) 直接嵌套退出(令牌);
    assert(豫言_影子根顶 == &帧);
    assert(豫言_直接退出顶 == &域);
    豫言_直接退出顶 = 域.前域;
    执行垃圾回收();
    assert(豫言值转整数(豫言值转元组(槽[2])[0]) == 73);
    豫言_离开影子根帧(&帧);
    assert(豫言_影子根顶 == NULL);
    执行垃圾回收();
    assert(豫言_当前分配指针 == 当前堆);
    free(当前堆);
    puts("影子根栈：移动更新、别名、嵌套提前退出及释放通过");
    return 0;
}
