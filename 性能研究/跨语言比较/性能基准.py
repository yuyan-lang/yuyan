import sys


def 斐波那契(数):
    if 数 < 2:
        return 数
    return 斐波那契(数 - 1) + 斐波那契(数 - 2)


def 素数筛(上限):
    是否质数 = bytearray(b"\x01") * (上限 + 1)
    是否质数[0] = 0
    是否质数[1] = 0
    质数 = 2
    while 质数 * 质数 <= 上限:
        if 是否质数[质数]:
            倍数 = 质数 * 质数
            while 倍数 <= 上限:
                是否质数[倍数] = 0
                倍数 += 质数
        质数 += 1
    个数 = 0
    数值 = 2
    while 数值 <= 上限:
        if 是否质数[数值]:
            个数 += 1
        数值 += 1
    return 个数


def 矩阵乘法(边长):
    总长 = 边长 * 边长
    矩阵甲 = [0] * 总长
    矩阵乙 = [0] * 总长
    矩阵丙 = [0] * 总长
    for 序数 in range(总长):
        行 = 序数 // 边长
        列 = 序数 - 行 * 边长
        矩阵甲[序数] = 行 + 列 + 1
        矩阵乙[序数] = 行 * 2 + 列 + 1
    for 行 in range(边长):
        行偏移 = 行 * 边长
        for 列 in range(边长):
            总和 = 0
            for 中间序数 in range(边长):
                总和 += 矩阵甲[行偏移 + 中间序数] * 矩阵乙[中间序数 * 边长 + 列]
            矩阵丙[行偏移 + 列] = 总和
    return 矩阵丙[0] + 矩阵丙[-1]


def 交换(数组, 左序, 右序):
    数组[左序], 数组[右序] = 数组[右序], 数组[左序]


def 分区(数组, 下界, 上界):
    中点 = 下界 + (上界 - 下界) // 2
    交换(数组, 中点, 上界)
    枢轴 = 数组[上界]
    存放序数 = 下界
    for 序数 in range(下界, 上界):
        if 数组[序数] < 枢轴:
            交换(数组, 序数, 存放序数)
            存放序数 += 1
    交换(数组, 存放序数, 上界)
    return 存放序数


def 快速排序(数组, 下界, 上界):
    if 下界 < 上界:
        分区序数 = 分区(数组, 下界, 上界)
        快速排序(数组, 下界, 分区序数 - 1)
        快速排序(数组, 分区序数 + 1, 上界)


def 快速排序基准(长度):
    数组 = list(range(长度, 0, -1))
    快速排序(数组, 0, 长度 - 1)
    return 数组[0] + 数组[长度 // 2] + 数组[-1]


def 主程序():
    if len(sys.argv) != 3:
        raise SystemExit(f"用法：{sys.argv[0]} <斐波那契|素数筛|矩阵乘法|快速排序> <规模>")
    算法 = sys.argv[1]
    规模 = int(sys.argv[2])
    函数表 = {
        "斐波那契": 斐波那契,
        "素数筛": 素数筛,
        "矩阵乘法": 矩阵乘法,
        "快速排序": 快速排序基准,
    }
    if 算法 not in 函数表:
        raise SystemExit(f"未知算法：{算法}")
    print(函数表[算法](规模))


if __name__ == "__main__":
    主程序()
