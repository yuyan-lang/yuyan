// 判断字符串一是否为字符串二的子串。
豫言值 豫言_是子字符串(豫言值 字符串一值, 豫言值 字符串二值) {
    const unsigned char *模式 = 豫言值转字节串指针(字符串一值);
    const unsigned char *文本 = 豫言值转字节串指针(字符串二值);
    uint64_t 模式长度 = 获取豫言_字符串长度(字符串一值);
    uint64_t 文本长度 = 获取豫言_字符串长度(字符串二值);
    if (模式长度 == 0) {
        return 爻转豫言值(true);
    }
    for (uint64_t 序数 = 0; 序数 + 模式长度 <= 文本长度; 序数++) {
        if (memcmp(文本 + 序数, 模式, 模式长度) == 0) {
            return 爻转豫言值(true);
        }
    }
    return 爻转豫言值(false);
}

