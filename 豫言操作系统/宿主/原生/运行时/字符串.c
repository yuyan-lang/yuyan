豫言值 豫言_字符串获取字节序数当前字符(豫言值 字符串值, 豫言值 序数值){
    char* 字符串 = 豫言值转字符串(字符串值);
    int64_t 序数 = 豫言值转整数(序数值);
    uint64_t 总长度 = 获取豫言_字符串长度(字符串值);
    if (序数 < 0 || (uint64_t)序数 >= 总长度) {
        报错并中止("取 UTF-8 字符：序数越界");
    }
    uint64_t 结束序数 = (uint64_t)序数 + 1;
    while (结束序数 < 总长度) {
        // 最高两位不是二进制“10”时，表示下一个 UTF-8 字符开始。
        if ((((unsigned char)字符串[结束序数]) & 0xC0) != 0x80) {
            break;
        }
        结束序数++;
    }
    uint64_t 长度 = 结束序数 - (uint64_t)序数;
    return 复制字节为豫言值(长度, 字符串 + 序数);
}

// 文言：\u 后随四位，皆十六进制方可，大小写不拘；有非者返负一。
// 汉语：把指针处的四个字符按十六进制解为 0 至 65535；任一字符不是十六进制数字则返回 -1。调用者须保证四个字节可读。
static int JSON四位十六进制(const char *指针) {
    int 值 = 0;
    for (int 位 = 0; 位 < 4; 位++) {
        unsigned char 字符 = (unsigned char)指针[位];
        int 数字;
        if (字符 >= '0' && 字符 <= '9') {
            数字 = 字符 - '0';
        } else if (字符 >= 'a' && 字符 <= 'f') {
            数字 = 字符 - 'a' + 10;
        } else if (字符 >= 'A' && 字符 <= 'F') {
            数字 = 字符 - 'A' + 10;
        } else {
            return -1;
        }
        值 = (值 << 4) | 数字;
    }
    return 值;
}

// 文言：码点书为 UTF-8，返其后之位。
// 汉语：把一个 Unicode 标量值写成一至四字节 UTF-8，返回写入后的输出指针；调用者须保证空间足够。
static char *JSON写UTF8字节(char *输出, uint32_t 码点) {
    if (码点 < 0x80) {
        *输出++ = (char)码点;
    } else if (码点 < 0x800) {
        *输出++ = (char)(0xC0 | (码点 >> 6));
        *输出++ = (char)(0x80 | (码点 & 0x3F));
    } else if (码点 < 0x10000) {
        *输出++ = (char)(0xE0 | (码点 >> 12));
        *输出++ = (char)(0x80 | ((码点 >> 6) & 0x3F));
        *输出++ = (char)(0x80 | (码点 & 0x3F));
    } else {
        *输出++ = (char)(0xF0 | (码点 >> 18));
        *输出++ = (char)(0x80 | ((码点 >> 12) & 0x3F));
        *输出++ = (char)(0x80 | ((码点 >> 6) & 0x3F));
        *输出++ = (char)(0x80 | (码点 & 0x3F));
    }
    return 输出;
}

// 开始序数 必须是引号，返回获取的字符串与前进的字符数
// 文言：识 \n \t \r \b \f \\ \/ \" 与 \uXXXX；代理项成对合为一码点，孤者代以 U+FFFD（EF BF BD）；\u0000 得字节零（串自带长度，不作串尾）；畸形转义中止。
// 汉语：与 WasmGC 运行时的 $json_string 行为一致。\uXXXX 转成 UTF-8：高代理项后紧随 \uDC00 至 \uDFFF 的低代理项时合并为一个码点（四字节）；孤立的高/低代理项替换为 U+FFFD；\u 后不足四位、含非十六进制字符或其他未知转义字符，均报错中止。
// 解码结果不会比源文本长（\uXXXX 六字节至多得三字节，代理对十二字节得四字节），故按源长分配缓冲区即足。
豫言值 豫言_字符串获取JSON字符串(豫言值 字符串值, 豫言值 开始序数值){
    char* 字符串 = 豫言值转字符串(字符串值);
    int64_t 开始序数 = 豫言值转整数(开始序数值);
    uint64_t 总长度 = 获取豫言_字符串长度(字符串值);
    if (开始序数 < 0 || (uint64_t)开始序数 >= 总长度) {
        报错并中止("JSON 字符串开始序数越界");
    }
    char *开始 = &字符串[开始序数];
    if (*开始 != '"'){
        报错并中止("JSON字符串必须以引号开始");
    }
    uint64_t 结束序数 = (uint64_t)开始序数 + 1;
    while (结束序数 < 总长度) {
        if (字符串[结束序数] == '\\') {
            结束序数 += 2;
            continue;
        }
        if (字符串[结束序数] == '"') {
            break;
        }
        结束序数++;
    }
    if (结束序数 >= 总长度 || 字符串[结束序数] != '"'){
        报错并中止("JSON字符串必须以引号结束");
    }
    char *结束 = 字符串 + 结束序数;
    int64_t 字节长度 = 结束-开始 + 1;
    char* 转义字符串 =  malloc(字节长度);
    char* 原指针 = 开始+1;
    char* 转义指针 = 转义字符串;
    // 第一遍已保证：每个反斜杠之后仍有字符，且该字符不是结束引号。
    while (原指针 < 结束) {
        if (*原指针 != '\\') {
            *转义指针++ = *原指针++;
            continue;
        }
        原指针 += 1;
        switch (*原指针)
        {
        case 'n':
            *转义指针++ = '\n';
            原指针 += 1;
            break;
        case 't':
            *转义指针++ = '\t';
            原指针 += 1;
            break;
        case 'r':
            *转义指针++ = '\r';
            原指针 += 1;
            break;
        case 'b':
            *转义指针++ = '\b';
            原指针 += 1;
            break;
        case 'f':
            *转义指针++ = '\f';
            原指针 += 1;
            break;
        case '\\':
            *转义指针++ = '\\';
            原指针 += 1;
            break;
        case '/':
            *转义指针++ = '/';
            原指针 += 1;
            break;
        case '"':
            *转义指针++ = '"';
            原指针 += 1;
            break;
        case 'u': {
            // 原指针指向 u；其后四个字节须都在结束引号之前，且都是十六进制数字。
            if (结束 - 原指针 < 5) {
                报错并中止("JSON字符串中的转义字符不合法");
                return 0;
            }
            int 单元 = JSON四位十六进制(原指针 + 1);
            if (单元 < 0) {
                报错并中止("JSON字符串中的转义字符不合法");
                return 0;
            }
            原指针 += 5;
            uint32_t 码点 = (uint32_t)单元;
            if (单元 >= 0xD800 && 单元 <= 0xDBFF) {
                // 高代理项：其后紧随 \uDC00 至 \uDFFF 则合并，否则视为孤立。
                码点 = 0xFFFD;
                if (结束 - 原指针 >= 6 && 原指针[0] == '\\' && 原指针[1] == 'u') {
                    int 低 = JSON四位十六进制(原指针 + 2);
                    if (低 >= 0xDC00 && 低 <= 0xDFFF) {
                        码点 = 0x10000 + (((uint32_t)单元 - 0xD800) << 10) + ((uint32_t)低 - 0xDC00);
                        原指针 += 6;
                    }
                }
            } else if (单元 >= 0xDC00 && 单元 <= 0xDFFF) {
                码点 = 0xFFFD;
            }
            转义指针 = JSON写UTF8字节(转义指针, 码点);
            break;
        }
        default:
            报错并中止("JSON字符串中的转义字符不合法");
            return 0;
        }
    }
    uint64_t 转义长度 = (uint64_t)(转义指针 - 转义字符串);
    豫言值 转义字符串值 = 复制字节为豫言值(转义长度, 转义字符串);
    free(转义字符串);
    return 元组转豫言值(2, (豫言值[]){转义字符串值, 整数转豫言值(字节长度)});
}

豫言值 豫言_获取通字符(豫言值 字符串地址) {
    const char* 开始 = 豫言值转字符串(字符串地址);
    const char* 结束 = 开始 + 获取豫言_字符串长度(字符串地址);

    // 统计 UTF-8 通字符数量。
    int 通字符数量 = 0;
    const char* 扫描指针 = 开始;
    while (扫描指针 != 结束) {
        if ((*扫描指针 & 0xC0) != 0x80) {
            通字符数量++;
        }
        扫描指针++;
    }

    // 为通字符分配堆数组。
    豫言值 通字符 = 分配豫言元组(通字符数量);

    // 提取各个通字符。
    扫描指针 = 开始;
    const char* 通字符开始 = 扫描指针;
    int 序数 = 0;
    while (扫描指针 != 结束) {
        if ((*扫描指针 & 0xC0) != 0x80) {
            if (扫描指针 != 通字符开始) {
                int 长度 = 扫描指针 - 通字符开始;
                豫言值 新字符值 = 复制字节为豫言值(长度, 通字符开始);
                写入元组(通字符, 序数, 新字符值);
                序数++;
            }
            通字符开始 = 扫描指针;
        }
        扫描指针++;
    }

    // 处理最后一个通字符。
    if (扫描指针 != 通字符开始) {
        int 长度 = 扫描指针 - 通字符开始;
        豫言值 新字符值 = 复制字节为豫言值(长度, 通字符开始);
        写入元组(通字符, 序数, 新字符值);
    }

    豫言值 返回值 =  元组转豫言值(2, (豫言值[]){通字符, 整数转豫言值(通字符数量)});
    验证豫言值(返回值, true, 0);
    return 返回值;
}

豫言值 豫言_字符串拼接(豫言值 字符串一值, 豫言值 字符串二值) {
    验证豫言值(字符串一值, true, 0);
    验证豫言值(字符串二值, true, 0);
    uint64_t 字符串一长度 = 获取豫言_字符串长度(字符串一值);
    uint64_t 字符串二长度 = 获取豫言_字符串长度(字符串二值);
    if (字符串一长度 > UINT32_MAX - 字符串二长度) {
        报错并中止("字符串拼接结果超过运行时长度上限");
    }
    uint64_t 结果长度 = 字符串一长度 + 字符串二长度;

    /* 文言：先根二串，配后复取。汉语：分配可能触发搬迁 GC，输入必须入根，不能沿用分配前的地址。 */
    volatile 豫言值 根[2];
    豫言影子根帧 帧 = {0};
    豫言_进入影子根帧(&帧, 根, 2);
    根[0] = 字符串一值;
    根[1] = 字符串二值;
    豫言值 返回值 = 分配豫言_字节串缓冲区(结果长度);
    char *结果字符串 = (char *)豫言值转字节串指针(返回值);
    memcpy(结果字符串, 豫言值转字符串(根[0]), 字符串一长度);
    memcpy(结果字符串 + 字符串一长度, 豫言值转字符串(根[1]), 字符串二长度);
    豫言_离开影子根帧(&帧);

    验证豫言值(返回值, true, 0);
    return 返回值;
}

豫言值 豫言_通字符拼接(豫言值 字符串列地址) {
    验证豫言值(字符串列地址, true, 0);
    const int 长度 = 获取同构列长度(字符串列地址);
    豫言值* 字符串组 = 获取同构列元素(字符串列地址);

    uint64_t 总长度 = 0;

    for (int 序数 = 0; 序数 < 长度; 序数++) {
        豫言值 当前字符串 = 字符串组[序数];
        uint64_t 当前长度 = 获取豫言_字符串长度(当前字符串);
        if (当前长度 > UINT32_MAX - 总长度) {
            报错并中止("通字符拼接结果超过运行时长度上限");
        }
        总长度 += 当前长度;
    }

    /* 文言：列先入根，配后重取其元。汉语：分配后从已更新的根重新取得列表和元素地址。 */
    volatile 豫言值 根[1];
    豫言影子根帧 帧 = {0};
    豫言_进入影子根帧(&帧, 根, 1);
    根[0] = 字符串列地址;
    豫言值 返回值 = 分配豫言_字节串缓冲区(总长度);
    字符串组 = 获取同构列元素(根[0]);

    char* 结果字符串 = (char *)豫言值转字节串指针(返回值);
    char* 当前位置 = 结果字符串;

    for (int 序数 = 0; 序数 < 长度; 序数++) {
        const char* 当前字符串 = 豫言值转字符串(字符串组[序数]);
        uint64_t 字符串长度 = 获取豫言_字符串长度(字符串组[序数]);
        memcpy(当前位置, 当前字符串, 字符串长度);
        当前位置 += 字符串长度;
    }

    assert((uint64_t)(当前位置 - 结果字符串) == 总长度);
    豫言_离开影子根帧(&帧);
    验证豫言值(返回值, true, 0);
    return 返回值;
}
