// 文言：判名直观其字节，不析字符列。汉语：源码打印的热点仅需检查 ASCII 数字和固定 UTF-8 定界符。
static bool 源码数字名(const char *名) {
    if (!*名) return false;
    for (const unsigned char *字 = (const unsigned char *)名; *字; ++字)
        if ((*字 < '0' || *字 > '9') && *字 != '-') return false;
    return true;
}
