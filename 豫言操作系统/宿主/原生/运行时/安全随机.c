#include "公共包含.h"
#include <sys/random.h>

/* 文言：一请至多二百五十六字节；汉语：getentropy 的单次请求上限为 256 字节。 */
#define 安全随机单次上限 256
/* 文言：节制单请之量，免外来数耗尽内存；汉语：限制一次请求为 1 MiB。 */
#define 安全随机总上限 (1024 * 1024)

豫言值 豫言_安全随机_字节串(豫言值 长度参数) {
    int64_t 长度 = 豫言值转整数(长度参数);
    if (长度 < 0 || 长度 > 安全随机总上限) {
        报错并中止("安全随机字节串：长度须在零至一兆之间");
    }

    豫言值 返回值 = 分配豫言_字节串缓冲区((uint64_t)长度);
    unsigned char *目标 = 豫言值转字节串指针(返回值);
    size_t 已取 = 0;
    while (已取 < (size_t)长度) {
        size_t 本次 = (size_t)长度 - 已取;
        if (本次 > 安全随机单次上限) {
            本次 = 安全随机单次上限;
        }
        if (getentropy(目标 + 已取, 本次) != 0) {
            /* 文言：熵不可取，则止；汉语：绝不回退到 rand 或零填充。 */
            报错并中止("安全随机字节串：操作系统取熵失败");
        }
        已取 += 本次;
    }
    return 返回值;
}
