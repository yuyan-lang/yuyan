#include "公共包含.h"

#include <poll.h>


enum {
    输入输出关注可读 = 1,
    输入输出关注可写 = 2,
};

enum {
    输入输出事件可读 = 1,
    输入输出事件可写 = 2,
    输入输出事件错误 = 4,
    输入输出事件挂断 = 8,
};


static 豫言值 构造多路等待结果(int64_t 状态, 豫言值 事件们) {
    return 元组转豫言值(2, (豫言值[]){
        整数转豫言值(状态),
        事件们,
    });
}

static 豫言值 构造多路等待错误(int 错误码) {
    return 构造多路等待结果(
        -(int64_t)错误码,
        数组转同构列(0, NULL)
    );
}


/*
 * 关注项是（文件描述符，关注事件）的同构列。返回值是
 * （状态码，各关注项实际发生的事件）的二元组；事件列与输入等长，
 * 零表示对应描述符尚未就绪。
 */
豫言值 豫言_异步_输入输出多路等待(豫言值 关注项们, 豫言值 超时毫秒数参数) {
    int64_t 超时毫秒数 = 豫言值转整数(超时毫秒数参数);
    uint64_t 关注项数 = 获取同构列长度(关注项们);

    if (超时毫秒数 < -1 || 超时毫秒数 > INT_MAX
        || 关注项数 > INT_MAX
        || 关注项数 > SIZE_MAX / sizeof(struct pollfd)
        || 关注项数 > SIZE_MAX / sizeof(豫言值)) {
        return 构造多路等待错误(EINVAL);
    }

    struct pollfd *描述符们 = NULL;
    豫言值 *事件们 = NULL;
    if (关注项数 > 0) {
        描述符们 = calloc((size_t)关注项数, sizeof(struct pollfd));
        事件们 = malloc((size_t)关注项数 * sizeof(豫言值));
        if (描述符们 == NULL || 事件们 == NULL) {
            free(描述符们);
            free(事件们);
            return 构造多路等待错误(ENOMEM);
        }
    }

    豫言值 *关注项数组 = 获取同构列元素(关注项们);
    for (uint64_t 序数 = 0; 序数 < 关注项数; ++序数) {
        豫言值 关注项 = 关注项数组[序数];
        int64_t 文件描述符 = 豫言值转整数(读取元组(关注项, 0));
        int64_t 关注事件 = 豫言值转整数(读取元组(关注项, 1));

        if (文件描述符 < 0 || 文件描述符 > INT_MAX
            || 关注事件 == 0
            || (关注事件 & ~(输入输出关注可读 | 输入输出关注可写)) != 0) {
            free(描述符们);
            free(事件们);
            return 构造多路等待错误(EINVAL);
        }

        描述符们[序数].fd = (int)文件描述符;
        if ((关注事件 & 输入输出关注可读) != 0) {
            描述符们[序数].events |= POLLIN;
        }
        if ((关注事件 & 输入输出关注可写) != 0) {
            描述符们[序数].events |= POLLOUT;
        }
    }

    int 等待结果;
    do {
        等待结果 = poll(描述符们, (nfds_t)关注项数, (int)超时毫秒数);
    } while (等待结果 < 0 && errno == EINTR);

    if (等待结果 < 0) {
        int 保存错误码 = errno;
        free(描述符们);
        free(事件们);
        return 构造多路等待错误(保存错误码);
    }

    for (uint64_t 序数 = 0; 序数 < 关注项数; ++序数) {
        int64_t 发生事件 = 0;
        short 原始事件 = 描述符们[序数].revents;
        if ((原始事件 & (POLLIN | POLLPRI)) != 0) {
            发生事件 |= 输入输出事件可读;
        }
        if ((原始事件 & POLLOUT) != 0) {
            发生事件 |= 输入输出事件可写;
        }
        if ((原始事件 & (POLLERR | POLLNVAL)) != 0) {
            发生事件 |= 输入输出事件错误;
        }
        if ((原始事件 & POLLHUP) != 0) {
            发生事件 |= 输入输出事件挂断;
        }
        事件们[序数] = 整数转豫言值(发生事件);
    }

    豫言值 事件列 = 数组转同构列(关注项数, 事件们);
    free(描述符们);
    free(事件们);
    return 构造多路等待结果(0, 事件列);
}
