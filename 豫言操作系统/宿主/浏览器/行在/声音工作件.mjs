// 文言：声出之工作件（AudioWorklet 之处理器，提案〇〇〇四三）：居音之线程，读工作线程所书之环形缓而奏之；缓空则补静音，
//   浏览器之采率异于开时所请者，则以线性插值重采。控制之字与书端（../构建/豫寓.mjs）同其布局。
// 汉语：声音输出的工作件（AudioWorklet 处理器，提案 00043）：在音频线程里读工作线程写好的环形缓冲并播放；缓冲空了补静音，
//   浏览器采样率与打开时请求的不同时按线性插值重采样。控制字与写入端（../构建/豫寓.mjs）同一布局：
//   共享缓冲的前 32 字节是八个三十二位整数——[0] 写帧位置（工作线程写）、[1] 读帧位置（本处理器写）、[2] 设备延迟帧（主线程写），
//   其后是从第 32 字节起的交错十六位小端样本。已播帧数就是读帧位置，以打开时请求的采样率计。
const 控制字 = 8, 样偏移 = 32;

class 豫寓鸣处理 extends AudioWorkletProcessor {
  constructor(项) {
    super();
    const 参 = 项.processorOptions;
    this.环 = new Int32Array(参.环, 0, 控制字);
    this.容量 = 参.容量;
    this.道 = 参.道;
    // 文言：每出一帧所耗之原帧数。汉语：每输出一帧所消耗的源帧数（源采样率除以设备采样率）。
    this.比 = 参.源率 / sampleRate;
    this.样 = new Int16Array(参.环, 样偏移, 参.容量 * 参.道);
    this.读 = 0;
    this.余 = 0;
  }

  // 文言：出一块：自读位起依比取原帧，线性插值；原帧尽则其余补静音。读位惟进已耗之整帧，故已播之数至末帧恰足。
  // 汉语：输出一块：从读位置起按比例取源帧线性插值；源帧用尽时其余补静音。读位置只推进已消耗的整帧，
  //   所以播到末帧时已播帧数恰好等于写入的帧数。
  process(入, 出) {
    const 道们 = 出[0];
    if (!道们?.length) return true;
    const 帧数 = 道们[0].length, 出数 = 道们.length;
    const 写 = Atomics.load(this.环, 0) >>> 0;
    const 有 = (写 - (this.读 >>> 0)) >>> 0;
    let 位 = this.读, 余 = this.余, 已出 = 0;
    for (; 已出 < 帧数; 已出++) {
      const 基 = Math.floor(余);
      if (基 >= 有) break;
      const 段甲 = (位 + 基) & (this.容量 - 1);
      // 文言：末帧无次帧可插，则以本帧充之。汉语：最后一帧没有下一帧可插值时用本帧顶替。
      const 段乙 = (位 + 基 + (基 + 1 < 有 ? 1 : 0)) & (this.容量 - 1);
      const 分 = 余 - 基;
      for (let 道 = 0; 道 < 出数; 道++) {
        const 源 = 道 < this.道 ? 道 : 0;
        const 甲 = this.样[段甲 * this.道 + 源], 乙 = this.样[段乙 * this.道 + 源];
        道们[道][已出] = (甲 + (乙 - 甲) * 分) / 32768;
      }
      余 += this.比;
    }
    for (; 已出 < 帧数; 已出++) for (const 道 of 道们) 道[已出] = 0;
    const 整 = Math.floor(余);
    位 += 整;
    this.余 = 余 - 整;
    this.读 = 位;
    if (整 > 0) Atomics.store(this.环, 1, 位 >>> 0);
    return true;
  }
}

registerProcessor('豫寓鸣', 豫寓鸣处理);
