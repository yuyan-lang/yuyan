// 文言：网页行在之单应用开机（云仓提案〇〇〇〇五）：既展快照，不起开机壳、不装诸部、不现编句子，径以预编之应用为初始之任而全窗行之；
//   地址栏之径作为命令行之参授之，应用闭则页面示其退。
// 汉语：网页行在的单应用开机（云仓提案 C00005）：展开快照之后不起开机壳、不装各部的登记脚本、不现编句子，直接把构建时预编好的应用
//   （豫行，即网页汇编模块）当初始任务全窗运行，把地址栏路径作为命令行参数交给它；应用退出后页面显示退出码。主站外壳用它启动阅读器一类应用。
//   只带运行时、应用与它用到的库：没有桌面、工具（豫构）与整套字体，故不与完整网页行在（行在.mjs）共用秘府、声音与终端。
import {构建文件系统, 展开归档, 取压缩归档} from '../构建/文件系统.mjs';
import {进程表} from '../构建/进程.mjs';
import {创建显示面表, 创建画布后端} from '../图形.mjs';

// 文言：单应之环境：缓存根定于 /tmp，不起将作；豫言行在为“网页”，宿主谓网页。汉语：单应用的环境：共享缓存根定在 /tmp/豫构缓存（应用不必编译，
//   这里只是与完整网页行在取同一个值），不起将作；豫言行在=网页，宿主是网页。
export const 单应用环境 = {豫言缓存目录: '/tmp/豫构缓存', 豫言将作: '关', 豫言行在: '网页', HOME: '/数据', USER: '网页'};

// 文言：单应用所需之能：跨源隔离、Worker 与 DecompressionStream；缺者列名而还。汉语：单应用开机需要跨源隔离（SharedArrayBuffer）、Worker 与
//   DecompressionStream；返回缺少的功能名，都支持时为空列表。
export function 单应用缺能(全局 = globalThis) {
  return [!全局.crossOriginIsolated && '跨源隔离（SharedArrayBuffer）', typeof 全局.Worker !== 'function' && 'Worker',
    typeof 全局.DecompressionStream !== 'function' && 'DecompressionStream'].filter(Boolean);
}

// 文言：起单应用：取诸快照、展于内存之文件系统（/工具 之类），立进程表与外务（惟显示面），起应用而全窗示之。
//   程序为豫言操作系统里的绝对路径（如 /工具/阅读器。豫行），参数们为交应用之命令行参数；出(流, 文) 受应用之出，报(文) 受进度，示屏(开) 告页入出全窗之面。
// 汉语：起单应用：取来各快照并展开到内存文件系统（/工具 等），建进程表与外务（只有显示面），启动应用并让页面全窗显示它的画面。
//   程序是豫言操作系统里的绝对路径（如 /工具/阅读器。豫行），参数们是交给应用的命令行参数；出(流, 文字) 收应用的输出，报(文字) 收进度，
//   示屏(开) 让页面进出全窗画面。
export async function 起单应用({快照们, 程序, 参数们 = [], 出 = () => {}, 报 = () => {}, 示屏 = () => {}, 根 = document, 全局 = globalThis}) {
  const 缺 = 单应用缺能(全局);
  if (缺.length) throw Error('此浏览器缺少单应用开机所需的能力：' + 缺.join('、'));
  const 系统 = new 构建文件系统();
  let 文件数 = 0;
  for (const 网址 of 快照们) {
    const 名 = decodeURIComponent(String(网址).split('/').pop().split('?')[0]);
    报('正在取 ' + 名);
    const 归档 = await 取压缩归档(网址, {报传输: 传输 => 报('正在取 ' + 名 + '：' + 传输.连接状态)});
    文件数 += 展开归档(系统, 归档, {目录: '/'}).文件数;
  }
  for (const 目 of ['/数据', '/系统', '/软件', '/tmp']) 系统.建目录(目);
  报('系统快照已展开：' + 文件数 + ' 个文件');
  const 桥模块 = await WebAssembly.compile(系统.读('/工具/节点值桥接.wasm'));
  const 表 = new 进程表({文件系统: 系统, 桥模块, 工作线程网址: new URL('../构建/工作线程.mjs', import.meta.url), 系统环境: 单应用环境});
  // 文言：屏：页画布“主窗口”，凡全窗并铺。外务惟显示面：单应用不用字体、剪贴、声出与子程序代办，应用问到则报未绑定。
  // 汉语：屏幕是页面里名为“主窗口”的画布，页面让它铺满窗口。外务只有显示面：单应用不用字体、剪贴板、声音输出与子程序代办，
  //   应用要这些接口时报“接口函数未绑定”（见 网页汇编/边界.mjs）。
  const 显示表 = 创建显示面表({后端: 创建画布后端({根, 全局})});
  表.外务 = {映: (记录, 操作, 号, 甲, 乙, 字节, 丙, 丁) => 显示表.调用(操作, 号, 甲, 乙, 字节, 丙, 丁)};
  const 解码们 = {1: new TextDecoder(), 2: new TextDecoder()};
  const 印 = (流, 值) => 出(流, 解码们[流].decode(值, {stream: true}));
  // 文言：先示全窗之面而后启应用：画面未示（页之样式藏之）则布局尺寸为零，应用量面即得“资源暂不可用”，一步都走不成。
  // 汉语：先把全窗画面显示出来再启动应用：画面没显示（页面的样式把它藏着）时布局尺寸是零，应用一量显示面就得到“资源暂不可用”，一步都走不成。
  示屏(true);
  let 号;
  try { 号 = await 表.启动(程序, 参数们, '/', 单应用环境, 0, 印); }
  catch (错) { 示屏(false); throw 错; }
  if (号 < 0) { 示屏(false); throw Error('应用起不来：' + 程序 + '，系统错误码：' + -号); }
  // 文言：应用既终，撤其全窗之面、除其录而还其退码。汉语：应用结束后撤下全窗画面、删去它的进程记录，并回报退出码。
  const 完成 = 表.候完成(号).then(记录 => {
    表.记录们.delete(记录.号);
    示屏(false);
    return 记录;
  });
  return {文件系统: 系统, 表, 号, 程序, 完成, 停止: () => 表.停止()};
}
