// 文言：网页行在（提案〇〇〇四三）：浏览器之标签即行在。展系统之快照于内存之文件系统（/源、/工具），以开机之壳（豫构交互）为首任务；任务各占一工作线程（同构建宿主之进程表），
//   行在于主线程办诸任务共用之事：显示面（页之画布）、字体、剪贴、屏与拟入、关机与重启；壳书“请求进入桌面”则起图形桌面之任务而授之以屏。页惟为屏与键。
// 汉语：网页行在（提案 00043）：浏览器标签页就是行在。把系统快照（/源 的源码与 /工具 的程序）展开到内存文件系统，起开机壳（豫构交互）为第一个任务；
//   每个任务占一个 Web Worker（沿用构建宿主的进程表与工作线程）。行在在主线程办各任务共用的事：显示面（页面画布，沿用 ../图形.mjs 的显示面表与画布后端）、
//   字体、剪贴板、读屏与合成输入、关机与重启；壳命令「图形」写下 /系统/请求进入桌面 时起图形桌面任务，把屏幕交给它。页面只当屏幕与键盘。
import {构建文件系统, 展开归档, 取压缩归档, 规范路径} from '../构建/文件系统.mjs';
import {进程表} from '../构建/进程.mjs';
import {创建显示面表, 创建画布后端, 创建字体能力, 事件种类} from '../图形.mjs';

// 文言：开机壳之环境：缓存根定于 /tmp，不起将作；豫言行在为“网页”，壳乃装行在诸部。汉语：开机壳的环境：共享缓存根定在 /tmp/豫构缓存，不起将作（构建服务）；豫言行在=网页，壳因而装行在的部（「图形」等）。
export const 开机环境 = {豫言缓存目录: '/tmp/豫构缓存', 豫言将作: '关', 豫言行在: '网页', HOME: '/数据', USER: '网页'};
export const 壳程序 = '/工具/豫构。豫行', 桌面程序 = '/工具/图形桌面。豫行';
const 请径 = '/系统/请求进入桌面', 标径 = '/系统/桌面运行中';

// 文言：行在所需之能。汉语：网页行在需要跨源隔离（SharedArrayBuffer）、Worker 与 DecompressionStream。
export function 行在缺能() {
  return [!globalThis.crossOriginIsolated && '跨源隔离（SharedArrayBuffer）', typeof Worker !== 'function' && 'Worker',
    typeof DecompressionStream !== 'function' && 'DecompressionStream'].filter(Boolean);
}

// 文言：HID 用法转语义键名与所出之文（美式键位）。汉语：HID 用法（键码）转成语义键名，可打印的另给出文字（美式键位，上档时取上排符号）；「拟键」用它。
const HID名 = {40: '回车', 41: '退出', 42: '退格', 43: '制表', 44: '空格', 59: '功能二', 74: '起首', 75: '上翻页', 76: '删除', 77: '末尾', 78: '下翻页', 79: '右', 80: '左', 81: '下', 82: '上',
  224: '控制', 225: '上档', 226: '交替', 227: '命令', 228: '控制', 229: '上档', 230: '交替', 231: '命令'};
const HID符 = {45: '-_', 46: '=+', 47: '[{', 48: ']}', 49: '\\|', 51: ';:', 52: '\'"', 53: '`~', 54: ',<', 55: '.>', 56: '/?'};
const HID数 = '1234567890', HID上数 = '!@#$%^&*()';
const 译HID = (用法, 上档) => {
  if (用法 >= 4 && 用法 <= 29) { const 字 = String.fromCharCode(97 + 用法 - 4); return {键: 字, 文: 上档 ? 字.toUpperCase() : 字}; }
  if (用法 >= 30 && 用法 <= 39) { const 序 = 用法 - 30; return {键: HID数[序], 文: 上档 ? HID上数[序] : HID数[序]}; }
  if (HID符[用法]) return {键: HID符[用法][0], 文: HID符[用法][上档 ? 1 : 0]};
  if (HID名[用法]) return {键: HID名[用法], 文: 用法 === 44 ? ' ' : ''};
  return null;
};

// 文言：起行在：取诸快照、展之、立进程表与行在之务、起开机壳而开其入。出(流, 文) 受壳之出，报(文) 受进度，示屏(开) 告页入出桌面。
// 汉语：起网页行在：取各快照并展开，建进程表与行在的外务，起开机壳并打开它的标准输入。出(流, 文字) 收壳的输出，报(文字) 收进度，示屏(开) 让页面进出桌面画面。
export async function 起行在({快照们, 出, 报 = () => {}, 示屏 = () => {}, 根 = document, 全局 = globalThis}) {
  const 缺 = 行在缺能();
  if (缺.length) throw Error('此浏览器缺少网页行在所需的能力：' + 缺.join('、'));
  const 系统 = new 构建文件系统();
  let 文件数 = 0;
  for (const 网址 of 快照们) {
    const 名 = decodeURIComponent(String(网址).split('/').pop().split('?')[0]);
    报('正在取 ' + 名);
    const 归档 = await 取压缩归档(网址, {报传输: 传输 => 报('正在取 ' + 名 + '：' + 传输.连接状态)});
    文件数 += 展开归档(系统, 归档, {目录: '/'}).文件数;
  }
  for (const 目 of ['/数据', '/系统', '/软件', '/tmp']) 系统.建目录(目);
  报('系统快照已展开：' + 文件数 + ' 个文件');
  const 桥模块 = await WebAssembly.compile(系统.读('/工具/节点值桥接.wasm'));
  const 表 = new 进程表({文件系统: 系统, 桥模块, 工作线程网址: new URL('../构建/工作线程.mjs', import.meta.url), 系统环境: 开机环境});
  const 解码们 = {1: new TextDecoder(), 2: new TextDecoder()};
  const 印 = (流, 值) => 出(流, 解码们[流].decode(值, {stream: true}));

  // 文言：屏：页之画布（data-yy-显示面="主窗口"）。截其建面之推，以供拟入。汉语：屏幕是页面里名为“主窗口”的画布；截下它建显示面时的“推”，合成输入（拟键等）由此进事件队列。
  const 画布后端 = 创建画布后端({根, 全局});
  let 屏面 = null, 屏推 = null, 指 = [0, 0], 钮位 = 0;
  const 后端 = {...画布后端, 建: (面, 值, 钩) => {
    const 败 = 画布后端.建(面, 值, 钩);
    if (!败 && 面.名 === '主窗口') {
      屏面 = 面; 屏推 = 钩.推;
      面.清理.push(() => { if (屏面 === 面) { 屏面 = null; 屏推 = null; } });
    }
    return 败;
  }};
  const 显示表 = 创建显示面表({后端});
  const 字体 = 创建字体能力({根, 全局});
  let 剪贴 = null, 已息 = false;

  // 文言：设备之务：息则止诸任务，更始则重载页，观屏读画布之素，拟键拟指拟钮入屏之事。汉语：设备操作：息停掉全部任务，更始重新载入页面，观屏读画布像素，拟键、拟指、拟钮把合成事件推进屏幕的事件队列。
  const 器务 = (操作, 甲, 乙, 丙) => {
    switch (操作) {
      case '息': 已息 = true; 表.停止(); 示屏(false); 出(2, '\n豫言系统已关机（重新载入页面即重新开机）。\n'); return 0;
      case '更始': 全局.location?.reload(); return 0;
      case '观屏': {
        const 画布 = 屏面?.画布;
        if (!画布 || !画布.width || !画布.height) return [2, 0, 0, new Uint8Array(0), '没有屏幕可读'];
        const 素 = 画布.getContext('2d').getImageData(0, 0, 画布.width, 画布.height).data;
        return [0, 画布.width, 画布.height, new Uint8Array(素.buffer, 素.byteOffset, 素.length)];
      }
      case '拟键': {
        if (!屏推) return 58;
        const 键 = 译HID(甲, (丙 & 0x22) !== 0);
        if (!键) return 0;
        屏推({种: 乙 ? 事件种类.按键按下 : 事件种类.按键抬起, 文: 键.键});
        if (乙 && 键.文 && !(丙 & 0x11) && !(丙 & 0x88)) 屏推({种: 事件种类.文字输入, 文: 键.文});
        return 0;
      }
      case '拟指': if (!屏推) return 58; 指 = [甲, 乙]; 屏推({种: 事件种类.指针移动, 甲, 乙}); return 0;
      case '拟钮': {
        if (!屏推) return 58;
        for (const [位, 钮] of [[1, 0], [4, 1], [2, 2]]) {
          const 新 = (甲 & 位) !== 0, 旧 = (钮位 & 位) !== 0;
          if (新 !== 旧) 屏推({种: 新 ? 事件种类.指针按下 : 事件种类.指针抬起, 甲: 指[0], 乙: 指[1], 丙: 钮});
        }
        钮位 = 甲;
        const 滚 = (乙 << 24) >> 24;
        if (滚) 屏推({种: 事件种类.滚轮, 甲: 指[0], 乙: 指[1], 丙: 0, 丁: Math.round(滚 * 48 * (Number(全局.devicePixelRatio) || 1))});
        return 0;
      }
      default: throw Error('未知的设备操作：' + 操作);
    }
  };
  表.外务 = {
    映: (记录, 操作, 号, 甲, 乙, 字节, 丙, 丁) => 显示表.调用(操作, 号, 甲, 乙, 字节, 丙, 丁),
    字体: (记录, 操作, 族名, 号, 偏移, 长度) => 字体.调用(操作, 族名, 号, 偏移, 长度),
    剪贴板写: (记录, 文) => { 剪贴 = String(文); },
    剪贴板读: () => [剪贴 !== null, 剪贴 ?? ''],
    器: (记录, 操作, 甲, 乙, 丙) => 器务(操作, 甲, 乙, 丙),
  };

  // 文言：桌面：壳书“请求进入桌面”（同裸机之开机壳与宿主之行在），行在删之、书“桌面运行中”、示屏而起图形桌面；桌面退则撤标而复命令行。
  // 汉语：桌面：壳命令「图形」写下 /系统/请求进入桌面（同裸机开机壳与宿主行在），行在删去它、写下 /系统/桌面运行中、让页面显示画布并起图形桌面任务；桌面退出后撤下标志、回到命令行。
  let 桌面号 = 0;
  const 起桌面 = async () => {
    if (桌面号 || 已息 || !系统.是文件(请径)) return;
    系统.删文件(请径);
    系统.写(标径, '1');
    示屏(true);
    桌面号 = await 表.启动(桌面程序, [], '/', {...开机环境}, 0, 印);
    if (桌面号 < 0) { 出(2, '行在：图形桌面起不来，系统错误码：' + -桌面号 + '\n'); 桌面号 = 0; 系统.删文件(标径); 示屏(false); return; }
    表.候完成(桌面号).then(记录 => {
      桌面号 = 0;
      if (系统.是文件(标径)) 系统.删文件(标径);
      if (记录.码) 出(2, '行在：图形桌面退出，退出码 ' + 记录.码 + '\n');
      示屏(false);
    });
  };
  const 原写 = 系统.写.bind(系统);
  系统.写 = (径, ...余) => { const 果 = 原写(径, ...余); if (规范路径(径) === 请径) queueMicrotask(起桌面); return 果; };

  const 号 = await 表.启动(壳程序, ['交互', '--直读', '--提示'], '/', 开机环境, 0, 印);
  if (号 < 0) throw Error('开机壳起不来，系统错误码：' + -号);
  表.开入(号);
  return {文件系统: 系统, 表, 壳号: 号, 送入: 行 => 表.送入(号, 行 + '\n'), 关入: () => 表.关入(号), 完成: 表.候完成(号)};
}
