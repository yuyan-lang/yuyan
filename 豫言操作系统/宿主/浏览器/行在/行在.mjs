  // 文言：盘之余（/数据、/系统、/软件 与根下之文）读自秘府；桌面之标开机则撤（同裸机“开机时标阴”）。
  // 汉语：盘上其余部分（/数据、/系统、/软件 与根目录下的文件）从秘府读入，之后的改动写回秘府；开机时撤下桌面运行标志（同裸机“开机时标阴”）。
  const 秘府 = await 接秘府(系统, {报错: 文 => 出(2, '行在：' + 文 + '\n')});
