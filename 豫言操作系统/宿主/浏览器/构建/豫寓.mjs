//   零是写帧位置，一是读帧位置（工作件写，即已播帧数），二是设备延迟帧数；样本从第 32 字节起，交错十六位小端。
const 声环容量 = 65536;
const 声流们 = new Map();
const 取声流 = 流 => 声流们.get(Number(流?.号 ?? 流));
// 文言：已播之帧：读位为三十二位之环，故记其已绕之数而累加之。汉语：已播帧数：读位置是三十二位计数，记下绕回的次数累加。
const 已播于 = 条 => {
  const 原 = Atomics.load(条.控制, 1) >>> 0;
  const 增 = (原 - 条.上读) >>> 0;
  if (增 > 0 && 增 < 0x80000000) { 条.已播 += 增; 条.上读 = 原; }
  return 条.已播;
};
// 文言：清声流：一程既毕，其流皆归行在就阖，本线程惟弃其表。汉语：清声流：一个程序跑完时它的流都由行在关掉，本线程只丢掉表。
