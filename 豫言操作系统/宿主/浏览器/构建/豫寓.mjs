//   寓误的支序：零未获授权、一资源暂不可用、二资源已失效、三资源不存在、四资源已存在、五资源配额已尽、六输入无效、七宿主操作失败（附文字）。

const 整 = 值 => BigInt(Math.trunc(Number(值)) || 0);
const 数 = 值 => Number(值?.小数 ?? 值);
const 空 = new Uint8Array(0);

// 文言：显示与字体之状态码（一至八，同 ../图形.mjs 之状态码）转为寓误。汉语：显示面表与字体能力的状态码（1–10，见 ../图形.mjs）转成寓误变体。
export const 码误 = (码, 文 = '') => (码 >= 1 && 码 <= 7 ? [码 - 1] : [7, String(文 || '宿主操作失败')]);
const 败 = (码, 文) => [1, 码误(码, 文)];
const 不可用 = () => [1, [1]];

// 文言：宿主之 JS 误转为寓误：不存则三，已存则四，余则七附其辞。汉语：宿主抛出的 JS 错误转成寓误：不存在为三，已存在为四，其余为七（附消息）。
const 错误误 = 错 => {
  const 文 = String(错?.message ?? 错);
  if (/不存在|ENOENT/u.test(文)) return [3];
  if (/已存在|EEXIST/u.test(文)) return [4];
  return [7, 文];
};

// 文言：事之种（../图形.mjs 之事件种类）对入事之支序。汉语：显示面表的事件种类编号（1–11）对应「入事」的支序（输入接口里的构造器次序）。
const 种支 = {1: 0, 2: 1, 3: 2, 4: 3, 5: 4, 6: 5, 8: 6, 7: 7, 9: 8, 10: 9, 11: 10};
// 文言：显示面表之果 [码, 种, 甲, 乙, 丙, 文, 丁] 之载化为入事：种、甲、乙、丙、文、丁。汉语：显示面表的事件结果 [码, 种, 甲, 乙, 丙, 文, 丁] 里的载荷转成「入事」。
const 入事载 = (种, 甲, 乙, 丙, 文, 丁) => {
  const 支 = 种支[种];
  switch (支) {
    case 0: case 1: case 2: return [支, 文];
    case 3: return [支, 整(甲), 整(乙)];
    case 4: case 5: return [支, 整(甲), 整(乙), 整(丙)];
    case 6: return [支, 整(甲), 整(乙), 整(丙), 整(丁)];
    case 10: return [支, 文, 整(甲)];
    case 7: case 8: case 9: return [支];
    default: return null;
  }
};
// 文言：显示面表之果 [码, 种, 甲, 乙, 丙, 文, 丁] 化为入取果。汉语：显示面表的事件结果 [码, 种, 甲, 乙, 丙, 文, 丁] 转成「入取果」。
const 入事果 = 果 => {
  if (果[0] !== 0) return 败(果[0], 果[5]);
  const [, 种, 甲, 乙, 丙, 文, 丁] = 果, 事 = 入事载(种, 甲, 乙, 丙, 文, 丁);
  return 事 ? [0, 事] : [1, [7, '未知的输入事件种类：' + 种]];
};

