// 文言：进程表之收尸与亲行承入（提案〇〇〇四三之五、六）：父退则子之录不留；亲行者子读父之入，子毕父续读。
// 汉语：进程表的收拾（父任务先退时子任务记录不残留，提案 00043 第六条）与亲行继承标准输入（第五条）：
//   父任务退出时删去已结束的子记录、把还在运行的儿子改挂初始任务；亲行让子进程读父进程的标准输入，子进程结束后父进程接着读余下的输入。
import test from 'node:test';
import assert from 'node:assert/strict';
import {进程表} from './进程.mjs';
import {构建文件系统} from './文件系统.mjs';

const 编码器 = new TextEncoder(), 解码器 = new TextDecoder();
// 文言：试之进程表：无桥模、无线程之址，只试记录之籍，不起工作者。汉语：测试用的进程表：不给桥模块与工作线程网址，只试记录的去留，不起工作线程。
const 新表 = () => new 进程表({文件系统: new 构建文件系统(), 桥模块: null, 工作线程网址: null, 系统环境: {}});

test('父任务退出时已结束的子记录删去、运行中的改挂初始任务', () => {
  const 表 = 新表();
  const 首 = 表.新记录(0, '壳', [], '/', {}, null);
  const 父 = 表.新记录(首.号, '桌面', [], '/', {}, null);
  const 已毕 = 表.新记录(父.号, '窗甲', [], '/', {}, null);
  const 未毕 = 表.新记录(父.号, '窗乙', [], '/', {}, null);
  表.结束(已毕, 0);
  assert.equal(表.记录们.has(已毕.号), true, '父未退时已结束的子记录留着等收取');
  表.结束(父, 0);
  assert.equal(表.记录们.has(已毕.号), false, '父退后已结束的子记录删去');
  assert.equal(表.记录们.get(未毕.号).父号, 首.号, '运行中的子任务改挂初始任务');
  表.结束(未毕, 0);
  assert.equal(表.记录们.has(未毕.号), false, '改挂的子任务结束后不再留存');
  assert.equal(表.记录们.has(首.号), true, '初始任务自己的记录照旧留着');
});

test('初始任务退出时子任务改挂到零，结束后也不留存', () => {
  const 表 = 新表();
  const 首 = 表.新记录(0, '壳', [], '/', {}, null);
  const 子 = 表.新记录(首.号, '会话', [], '/', {}, null);
  表.结束(首, 0);
  assert.equal(表.记录们.get(子.号).父号, 0, '初始任务退了，子任务无所依即改挂零');
  表.结束(子, 0);
  assert.equal(表.记录们.has(子.号), false, '失去收取者的子记录结束时删去');
});

test('亲行让子进程读父进程的标准输入，子结束后父接着读', async () => {
  const 表 = 新表();
  const 父 = 表.新记录(0, '壳', [], '/', {}, null);
  表.开入(父.号, {终端: true});
  let 子号 = 0;
  // 文言：代启动：立子之录而读一行，以其行入于出，退码零。汉语：替身启动：建子记录读一行，把读到的行写进标准输出，退出码零。
  表.启动 = async (程序, 参数, 目录, 环境, 父号, 观察者, 承入) => {
    const 子 = 表.新记录(父号, 程序, 参数, 目录, 环境, 观察者);
    子号 = 子.号;
    if (承入) 子.入 = 承入;
    (async () => {
      const [有, 行] = await 表.读行(子);
      表.收输出(子, 1, 编码器.encode(有 ? 行 + '\n' : ''));
      表.结束(子, 有 ? 0 : 3);
    })();
    return 子.号;
  };
  const 候 = 表.亲行(父.号, '子验收', [], '/', {});
  表.送入(父.号, '子一行\n父续行\n');
  const 果 = await 候;
  assert.equal(果[0], 0, '子程序读到输入，退出码零');
  assert.equal(解码器.decode(果[1]), '子一行\n', '子进程读走父进程输入的第一行');
  assert.equal(表.记录们.has(子号), false, '亲行的子记录已收走');
  const [有, 行] = await 表.读行(表.记录们.get(父.号));
  assert.equal(有, true, '父进程的输入没被子进程关掉');
  assert.equal(行, '父续行', '父进程接着读剩下的输入');
});

test('亲行直通时子进程的输出随出转给父进程的观察者', async () => {
  const 表 = 新表();
  const 见 = [];
  const 父 = 表.新记录(0, '壳', [], '/', {}, (流, 值) => 见.push([流, 解码器.decode(值)]));
  表.开入(父.号, {终端: true});
  表.启动 = async (程序, 参数, 目录, 环境, 父号, 观察者, 承入) => {
    const 子 = 表.新记录(父号, 程序, 参数, 目录, 环境, 观察者);
    if (承入) 子.入 = 承入;
    (async () => {
      await 表.读行(子);
      表.收输出(子, 1, 编码器.encode('子出\n'));
      表.收输出(子, 2, 编码器.encode('子误\n'));
      表.结束(子, 0);
    })();
    return 子.号;
  };
  const 候 = 表.亲行(父.号, '子验收', [], '/', {}, true);
  表.送入(父.号, '子一行\n');
  const 果 = await 候;
  assert.equal(果[0], 0, '子程序退出码零');
  assert.equal(果[1].length, 0, '直通时不再收存标准输出');
  assert.equal(果[2].length, 0, '直通时不再收存标准错误');
  assert.deepEqual(见, [[1, '子出\n'], [2, '子误\n']], '输出随出转给父进程的观察者');
});

test('父进程没有开输入时亲行的子进程一读即尽', async () => {
  const 表 = 新表();
  const 父 = 表.新记录(0, '构建', [], '/', {}, null);
  表.启动 = async (程序, 参数, 目录, 环境, 父号, 观察者, 承入) => {
    const 子 = 表.新记录(父号, 程序, 参数, 目录, 环境, 观察者);
    if (承入) 子.入 = 承入;
    (async () => {
      const [有] = await 表.读行(子);
      表.结束(子, 有 ? 0 : 3);
    })();
    return 子.号;
  };
  const 果 = await 表.亲行(父.号, '子验收', [], '/', {});
  assert.equal(果[0], 3, '没有输入的父进程，子进程读到输入结束');
});
