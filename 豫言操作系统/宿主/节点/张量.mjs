    const 温度 = 数值(温度值), 前k = Number(前k值), 累积p = 数值(累积p值);
    if (!(温度 > 0)) return 最大下标(甲);
    const 值们 = 视(甲.存, 'f32'), 总 = 甲.数, 分 = new Float64Array(总);
    // 文言：NaN 之序置于末。汉语：排序时 NaN 当作负无穷（规范未定，待办事项）。
