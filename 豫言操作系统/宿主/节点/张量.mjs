// 文言：化为脑浮点：先成单精，再舍其低十六位而取偶。汉语：转为 bfloat16：先成单精度，再对低 16 位就近取偶；NaN 保持为安静 NaN。待办事项：三十二位整数绝对值逾 2^24 时两次舍入，可能与直接舍入差一个最低位。
