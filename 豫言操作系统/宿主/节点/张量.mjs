// 文言：Philox 一块：十轮，每轮后钥增黄金比之数。汉语：Philox4x32-10 算一块，结果写进 出（Uint32Array，4 项）：十轮，每轮之间密钥加 0x9E3779B9、0xBB67AE85。
function 菲洛块(钥0, 钥1, 计0, 计1, 出) {
  let c0 = 计0 >>> 0, c1 = 计1 >>> 0, c2 = 0, c3 = 0, k0 = 钥0 >>> 0, k1 = 钥1 >>> 0;
  for (let 轮 = 0; 轮 < 10; 轮++) {
    if (轮 > 0) { k0 = (k0 + 0x9e3779b9) >>> 0; k1 = (k1 + 0xbb67ae85) >>> 0; }
    const 高0 = 乘高(0xd2511f53, c0), 低0 = Math.imul(0xd2511f53, c0) >>> 0;
    const 高1 = 乘高(0xcd9e8d57, c2), 低1 = Math.imul(0xcd9e8d57, c2) >>> 0;
    c0 = (高1 ^ c1 ^ k0) >>> 0;
    c1 = 低1;
    c2 = (高0 ^ c3 ^ k1) >>> 0;
    c3 = 低0;
  }
  出[0] = c0; 出[1] = c1; 出[2] = c2; 出[3] = c3;
}
