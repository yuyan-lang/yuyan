      const 行字节 = 字节数(乙类, 深), 块数 = 深 / 类表[乙类].块长;
      const 字 = 是块(乙类) ? 视(乙.存, 'u8') : null, 符字 = 是块(乙类) ? 视(乙.存, 'i8') : null;
