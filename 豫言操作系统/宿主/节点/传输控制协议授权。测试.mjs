// 汉语：硬验拒绝未授端点及外来句柄，并保留连接等待、接受登记和清理语义。文言：实验未授端点与外来柄之拒，且存连接之候、受柄之录及清理之义。
import assert from 'node:assert/strict';
import {创建传输控制协议授权} from './传输控制协议授权.mjs';
const 调用 = [];
const 原语 = new Proxy({}, {get: (_, 名) => (...参) => {
  调用.push([名, ...参]);
  if (名 === '开门') return [0, 41];
  if (名 === '叩门') return [1, 42];
  if (名 === '迎') return [0, 43];
  if (名 === '投书') return [0, new Uint8Array([1, 2])];
  return [0, 0];
}});
const 网络 = 创建传输控制协议授权({授权: {源: new Set(['http://127.0.0.1:8123']), 全部来源: false}, 原语});
assert.deepEqual(网络.能力.开门('127.0.0.1', 8124, 128), [-1, -1]);
assert.equal(调用.length, 0);
assert.deepEqual(网络.能力.开门('127.0.0.1', 8123, 128), [0, 41]);
assert.deepEqual(网络.能力.叩门('127.0.0.1', 8123), [1, 42]);
assert.deepEqual(网络.能力.迎(41), [0, 43]);
assert.deepEqual(网络.能力.别(0), [-8, null]);
assert.equal(网络.能力.听帛(0, 1)[0], -8);
assert.deepEqual(Array.from(网络.能力.投书('127.0.0.1', 8123, 10, new Uint8Array())[1]), [1, 2]);
assert.equal(网络.能力.投书('127.0.0.1', 53, 10, new Uint8Array())[0], -1);
网络.关闭();
assert.equal(调用.filter(项 => 项[0] === '别').length, 3);
assert.equal(网络.能力.守候(41, 1, 0)[0], -8);
const 全源 = 创建传输控制协议授权({授权: {源: new Set(), 全部来源: true}, 原语});
assert.equal(全源.能力.叩门('127.0.0.1', 8123)[0], 1);
assert.equal(全源.能力.开门('127.0.0.1', 8123, 128)[0], -1);
全源.关闭();
console.log('传输控制协议授权与句柄清理通过');
