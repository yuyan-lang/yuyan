// 汉语：硬验拒绝未授端点及外来句柄，并保留连接等待、接受登记和清理语义。文言：实验未授端点与外来柄之拒，且存连接之候、受柄之录及清理之义。
import assert from 'node:assert/strict';
import {创建传输控制协议授权} from './传输控制协议授权.mjs';
const 调用 = [];
const 原语 = new Proxy({}, {get: (_, 名) => (...参) => {
  调用.push([名, ...参]);
  if (名 === '传输控制协议_监听') return [0, 41];
  if (名 === '传输控制协议_开始连接') return [1, 42];
  if (名 === '传输控制协议_接受') return [0, 43];
  if (名 === '数据报_交换') return [0, new Uint8Array([1, 2])];
  return [0, 0];
}});
const 网络 = 创建传输控制协议授权({授权: {源: new Set(['http://127.0.0.1:8123']), 全部来源: false}, 原语});
assert.deepEqual(网络.能力.传输控制协议_监听('127.0.0.1', 8124, 128), [-1, -1]);
assert.equal(调用.length, 0);
assert.deepEqual(网络.能力.传输控制协议_监听('127.0.0.1', 8123, 128), [0, 41]);
assert.deepEqual(网络.能力.传输控制协议_开始连接('127.0.0.1', 8123), [1, 42]);
assert.deepEqual(网络.能力.传输控制协议_接受(41), [0, 43]);
assert.deepEqual(网络.能力.传输控制协议_关闭(0), [-8, null]);
assert.equal(网络.能力.传输控制协议_读取字节串(0, 1)[0], -8);
assert.deepEqual(Array.from(网络.能力.数据报_交换('127.0.0.1', 8123, 10, new Uint8Array())[1]), [1, 2]);
assert.equal(网络.能力.数据报_交换('127.0.0.1', 53, 10, new Uint8Array())[0], -1);
网络.关闭();
assert.equal(调用.filter(项 => 项[0] === '传输控制协议_关闭').length, 3);
assert.equal(网络.能力.传输控制协议_等待(41, 1, 0)[0], -8);
const 全源 = 创建传输控制协议授权({授权: {源: new Set(), 全部来源: true}, 原语});
assert.equal(全源.能力.传输控制协议_开始连接('127.0.0.1', 8123)[0], 1);
assert.equal(全源.能力.传输控制协议_监听('127.0.0.1', 8123, 128)[0], -1);
全源.关闭();
console.log('传输控制协议授权与句柄清理通过');
