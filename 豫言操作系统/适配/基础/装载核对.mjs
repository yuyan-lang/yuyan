// 文言：源级接口与客器投影各核其据；汉语：分别核对公共接口清单和本轮 Wasm 宿主桥形状。
const 须 = (条件, 消息) => {
  if (!条件) throw new Error(`豫言操作系统装载失败：${消息}`);
};

const 函数键 = 项 => `${项.模块}/${项.函数}/${项.方向}/${项.签名}`;
const 身份键 = 项 => 项 ? `${项.所有者}/${项.名称}/${项.版本}` : '';
const 核对闭包 = (清单, 所需) => {
  const 已解析 = 清单.解析闭包;
  须(Array.isArray(已解析) && 已解析.length === 所需.length, '解析依赖闭包不符');
  须(所需.every((身份, 序) => 身份键(已解析[序]) === 身份), '解析依赖身份或顺序不符');
};
const 核对规范摘要 = (清单, 包描述名) => {
  const 摘要 = 清单.规范摘要;
  须(Array.isArray(摘要) && 摘要.length > 0, '缺少规范文件摘要');
  const 文件名们 = new Set();
  for (const 项 of 摘要) {
    须(typeof 项?.文件 === 'string' && 项.算法 === 'SHA-256' &&
      typeof 项.摘要 === 'string' && /^[0-9a-f]{64}$/u.test(项.摘要), '规范文件摘要格式不符');
    须(!文件名们.has(项.文件), '规范文件摘要重复');
    文件名们.add(项.文件);
  }
  须([...文件名们].some(名 => /^包\/[^/]+。(?:应用)?接口。豫$/u.test(名)), '缺少接口文件摘要');
  for (const 名 of [`包/${包描述名}。包。豫`,
    '公共/执行契约.汉语.md', '公共/执行契约.文言.md']) {
    须(文件名们.has(名), `缺少规范文件摘要：${名}`);
  }
};

export function 核对首批接口装载({程序模块, 应用要求, 宿主提供, 应用入口 = null, 投影}) {
  须(程序模块 instanceof WebAssembly.Module, '程序不是已编译的 Wasm 模块');
  须(应用要求?.格式版本 === 4 && 宿主提供?.格式版本 === 4, '基础接口清单格式不符');
  须(应用要求.接口所有者 === '豫言' && 应用要求.接口名称 === '豫言操作系统基础', '应用要求的基础包身份不符');
  须(应用要求.接口版本 === '0.1.0', '应用要求的基础包版本不符');
  核对闭包(应用要求, ['豫言/豫言操作系统基础/0.1.0', '豫言/标准库/0.1.0']);
  核对规范摘要(应用要求, '豫言操作系统基础');
  须(JSON.stringify(应用要求) === JSON.stringify(宿主提供), '宿主提供的基础包清单与应用要求不符');

  // 文言：首批二术须皆由宿主供，型与向同；汉语：核对首批诊断和单调时钟的源级签名及方向。
  const 基础函数 = new Set(应用要求.函数?.map(函数键));
  须(基础函数?.has('诊断/记录诊断/宿主/→[「 字符串 」；「 有 」]'), '缺少诊断函数或签名不符');
  须(基础函数.has('时钟/读取单调微秒/宿主/→[「 有 」；「 整数 」]'), '缺少单调时钟函数或签名不符');

  if (应用入口 !== null) {
    须(应用入口.格式版本 === 4 && 应用入口.接口所有者 === '豫言' &&
      应用入口.接口名称 === '豫言操作系统启动' && 应用入口.接口版本 === '0.1.0', '应用入口包身份不符');
    核对闭包(应用入口, [
      '豫言/豫言操作系统启动/0.1.0', '豫言/标准库/0.1.0', '豫言/豫言操作系统基础/0.1.0'
    ]);
    核对规范摘要(应用入口, '豫言操作系统启动');
    须(应用入口.函数?.some(项 => 函数键(项) === '程序入口/启动程序/应用/→[「 有 」；「 有 」]'),
      '应用入口方向或签名不符');
  }

  // 文言：源术与标准原语之配载适配侧，不混入公约；汉语：源级映射由适配包声明，Wasm 形状由成品独立核对。
  须(投影?.格式版本 === 1 && 投影.适配包?.所有者 === '豫言' &&
    投影.适配包.名称 === '豫言操作系统基础适配' && 投影.适配包.版本 === '0.1.0', '适配投影身份不符');
  const 期望函数 = [
    ['诊断', '记录诊断', '记录诊断', '打印行', '豫言_打印行'],
    ['时钟', '读取单调微秒', '读取单调微秒', '获取当前纳秒时间', '豫言_获取当前纳秒时间']
  ];
  须(Array.isArray(投影.宿主函数) && 投影.宿主函数.length === 期望函数.length &&
    期望函数.every((预期, 序) => {
      const 项 = 投影.宿主函数[序];
      return [项?.接口模块, 项?.接口函数, 项?.豫言适配函数, 项?.标准库函数, 项?.宿主原语]
        .every((值, 位) => 值 === 预期[位]);
    }), '宿主函数投影记录不符');
  须(Array.isArray(投影.Wasm导入) && 投影.Wasm导入.length === 1 &&
    投影.Wasm导入[0].模块 === 'yuyan:gc-host/v1' && 投影.Wasm导入[0].名称 === 'call' &&
    投影.Wasm导入[0].种类 === 'function', 'Wasm 导入投影记录不符');
  须(Array.isArray(投影.Wasm导出) && 投影.Wasm导出.length === 1 &&
    投影.Wasm导出[0].名称 === '_start' && 投影.Wasm导出[0].种类 === 'function' &&
    投影.Wasm导出[0].豫言层 === '程序顶层', 'Wasm 导出投影记录不符');
  const 导入 = WebAssembly.Module.imports(程序模块);
  const 导出 = WebAssembly.Module.exports(程序模块);
  须(导入.length === 投影.Wasm导入.length &&
    导入.every((项, 序) => 项.module === 投影.Wasm导入[序].模块 &&
      项.name === 投影.Wasm导入[序].名称 && 项.kind === 投影.Wasm导入[序].种类), 'Wasm 宿主导入形状不符');
  须(导出.some(项 => 项.name === 投影.Wasm导出[0].名称 &&
    项.kind === 投影.Wasm导出[0].种类), 'Wasm 缺少启动导出');
  return true;
}
